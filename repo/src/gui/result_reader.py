def read_analysis_results(output_dir: Path, requested_algorithm: str, levels: int) -> dict[str, AlgorithmResult]:
    requested_algorithm = requested_algorithm.upper()
    if requested_algorithm != "ALL":
        summary = output_dir / "summary.csv"
        metrics = _normalize_metrics(_read_csv_first_row(summary), _SINGLE_MAP) if summary.exists() else {}
        return {
            requested_algorithm: AlgorithmResult(
                algorithm=requested_algorithm,
                segmented_image=_existing(output_dir / "segmented.png"),
                histogram_image=_existing(output_dir / "histogram.png"),
                convergence_image=_existing(output_dir / "convergence.png") or _first(output_dir / "convergence", f"{requested_algorithm}_thr{levels}_run*_convergence.png"),
                metrics=metrics,
            )
        }

    results: dict[str, AlgorithmResult] = {}
    for algo in ("DE", "DESSA", "SDE", "GWO", "PSO", "CSA", "FA"):
        algo_dir = output_dir / f"Results_{algo}"
        if not algo_dir.exists():
            continue

        segmented = _first(algo_dir / "imgResults", f"Segmented_*_thr{levels}.png")
        histogram = _first(algo_dir, f"{algo}_*_thr{levels}_hist.png")
        convergence = _first(algo_dir, f"{algo}_*_thr{levels}_convergence.png")

        csv_table = algo_dir / f"Batch_{algo}_Mth.csv"
        xlsx_table = algo_dir / f"Batch_{algo}_Mth.xlsx"
        raw: dict[str, str] = {}
        if csv_table.exists():
            raw = _read_csv_first_row(csv_table)
        elif xlsx_table.exists():
            raw = _read_xlsx_first_row(xlsx_table)

        results[algo] = AlgorithmResult(
            algorithm=algo,
            segmented_image=segmented,
            histogram_image=histogram,
            convergence_image=convergence,
            metrics=_normalize_metrics(raw, _BATCH_MAP),
        )

    return results


def _existing(path: Path) -> Path | None:
    return path if path.exists() else None


def _first(folder: Path, pattern: str) -> Path | None:
    if not folder.exists():
        return None
    matches = sorted(folder.glob(pattern))
    return matches[0] if matches else None


def _read_csv_first_row(path: Path) -> dict[str, str]:
    try:
        with path.open("r", encoding="utf-8-sig", newline="") as handle:
            reader = csv.DictReader(handle)
            row = next(reader, None)
            return {str(k): str(v) for k, v in (row or {}).items() if k is not None}
    except (OSError, csv.Error):
        return {}


def _read_xlsx_first_row(path: Path) -> dict[str, str]:
    """Read the first data row of the simple XLSX generated by libxlsxwriter.

    This avoids adding a large spreadsheet dependency to the Raspberry Pi GUI.
    It is intentionally small and only targets the table shape emitted by the
    project's existing ``write_results_table`` function.
    """

    try:
        with zipfile.ZipFile(path, "r") as archive:
            shared = _xlsx_shared_strings(archive)
            sheet_xml = archive.read("xl/worksheets/sheet1.xml")
    except (OSError, KeyError, zipfile.BadZipFile):
        return {}

    ns = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
    try:
        root = ET.fromstring(sheet_xml)
    except ET.ParseError:
        return {}

    rows = root.findall(".//m:sheetData/m:row", ns)
    if len(rows) < 2:
        return {}

    headers = _xlsx_row_values(rows[0], shared, ns)
    values = _xlsx_row_values(rows[1], shared, ns)
    return {headers[i]: values[i] if i < len(values) else "" for i in range(len(headers)) if headers[i]}


def _xlsx_shared_strings(archive: zipfile.ZipFile) -> list[str]:
    try:
        raw = archive.read("xl/sharedStrings.xml")
    except KeyError:
        return []

    ns = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
    try:
        root = ET.fromstring(raw)
    except ET.ParseError:
        return []

    strings: list[str] = []
    for item in root.findall("m:si", ns):
        text = "".join(node.text or "" for node in item.findall(".//m:t", ns))
        strings.append(text)
    return strings


def _xlsx_row_values(row: ET.Element, shared: list[str], ns: dict[str, str]) -> list[str]:
    values: list[str] = []
    for cell in row.findall("m:c", ns):
        kind = cell.attrib.get("t", "")
        value_node = cell.find("m:v", ns)
        inline = cell.find("m:is/m:t", ns)

        if kind == "inlineStr" and inline is not None:
            value = inline.text or ""
        elif value_node is None:
            value = ""
        elif kind == "s":
            try:
                value = shared[int(value_node.text or "0")]
            except (ValueError, IndexError):
                value = value_node.text or ""
        else:
            value = value_node.text or ""
        values.append(value)
    return values


def _normalize_metrics(raw: dict[str, str], mapping: dict[str, str]) -> dict[str, str]:
    normalized: dict[str, str] = {}
    for source, target in mapping.items():
        if source in raw:
            normalized[target] = raw[source]
    return normalized
